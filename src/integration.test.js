import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import bcrypt from 'bcryptjs';
import { pool } from './db.js';
import { route, bootstrap } from './main.js';
import { runSetup } from './setup.js';

test('회원 권한과 예약 차감, DB 중복 제약을 함께 확인한다',async()=>{
  const db=new PGlite();
  await db.exec(await fs.readFile(new URL('../db/001-init.sql',import.meta.url),'utf8'));
  await db.exec("SET TIME ZONE 'Asia/Seoul'");
  const originalQuery=pool.query.bind(pool), originalConnect=pool.connect.bind(pool);
  pool.query=(q,p)=>db.query(q,p);
  pool.connect=async()=>({query:(q,p)=>db.query(q,p),release(){}});
  const call=(path,method='GET',body={},token)=>route({path,method,body,query:{},headers:token?{authorization:'Bearer '+token}:{}});
  let app, setupDb;
  try{
    const member1=await call('/auth/signup','POST',{name:'가상회원1',email:'member1@example.test',phone:'01000000001',password:'TestPassword123!'});
    const member2=await call('/auth/signup','POST',{name:'가상회원2',email:'member2@example.test',phone:'01000000002',password:'TestPassword123!'});
    const stored=(await db.query("SELECT password_hash FROM hw2.accounts WHERE email='member1@example.test'")).rows[0];
    assert.notEqual(stored.password_hash,'TestPassword123!');
    assert.equal(await bcrypt.compare('TestPassword123!',stored.password_hash),true);
    await assert.rejects(call('/staff','GET',{},member1.token),e=>e.status===403);
    await assert.rejects(call('/auth/signup','POST',{name:'중복',email:'MEMBER1@example.test',phone:'01000000003',password:'TestPassword123!'}),e=>e.code==='23505');
    const admin=(await db.query("INSERT INTO hw2.accounts(email,name,role,password_hash) VALUES('admin@example.test','관장','ADMIN',$1) RETURNING id",[await bcrypt.hash('AdminPassword123!',4)])).rows[0];
    const loggedAdmin=await call('/auth/login','POST',{email:'admin@example.test',password:'AdminPassword123!'});
    const staff=await call('/staff','POST',{name:'트레이너',email:'staff@example.test',role:'STAFF'},loggedAdmin.token);
    const staffLogin=await call('/auth/login','POST',{email:'staff@example.test',password:staff.temporaryPassword});
    await assert.rejects(call('/dashboard','GET',{},staffLogin.token),e=>e.status===403);
    const changed=await call('/auth/password','POST',{currentPassword:staff.temporaryPassword,newPassword:'NewPassword123!'},staffLogin.token);
    await assert.rejects(call('/auth/me','GET',{},staffLogin.token),e=>e.status===401);
    const t=await call('/trainers','POST',{accountId:staff.account.id,weekdays:[0,1,2,3,4,5,6]},loggedAdmin.token);
    const type=await call('/pass-types','POST',{name:'테스트 1회권',sessions:1,listPrice:50000,durationDays:30},loggedAdmin.token);
    const memberRows=await call('/members','GET',{},loggedAdmin.token);
    const m1=memberRows.find(m=>m.name==='가상회원1'),m2=memberRows.find(m=>m.name==='가상회원2');
    const today=new Date(Date.now()+9*3600000).toISOString().slice(0,10);
    const tomorrow=new Date(Date.now()+9*3600000+86400000).toISOString().slice(0,10);
    const p1=await call('/passes','POST',{memberId:m1.id,passTypeId:type.id,purchasedOn:today,paidAmount:45000},loggedAdmin.token);
    const p2=await call('/passes','POST',{memberId:m2.id,passTypeId:type.id,purchasedOn:today,paidAmount:50000},loggedAdmin.token);
    const slot=tomorrow+'T10:00:00+09:00';
    await assert.rejects(call('/bookings','POST',{passId:p2.id,trainerId:t.id,startsAt:slot},member1.token),e=>e.status===403);
    const b=await call('/bookings','POST',{passId:p1.id,trainerId:t.id,startsAt:slot},member1.token);
    assert.equal((await call('/passes','GET',{},member1.token))[0].available_to_book,0);
    assert.equal((await call('/passes','GET',{},member1.token))[0].remaining_sessions,1);
    await assert.rejects(call('/bookings','POST',{passId:p1.id,trainerId:t.id,startsAt:tomorrow+'T11:00:00+09:00'},member1.token),/予約|예약/);
    await assert.rejects(call('/bookings','POST',{passId:p2.id,trainerId:t.id,startsAt:slot},member2.token),e=>e.code==='23505');
    await assert.rejects(call('/bookings/'+b.id,'PATCH',{status:'CANCELLED'},member2.token),e=>e.status===403);
    assert.equal((await call('/bookings','GET',{},member2.token)).length,0);
    await call('/bookings/'+b.id,'PATCH',{status:'CANCELLED'},member1.token);
    assert.equal((await call('/passes','GET',{},member1.token))[0].available_to_book,1);
    const b2=await call('/bookings','POST',{passId:p1.id,trainerId:t.id,startsAt:slot},member1.token);
    await db.query("UPDATE hw2.bookings SET starts_at=date_trunc('hour',now())-interval '1 hour' WHERE id=$1",[b2.id]);
    await call('/bookings/'+b2.id,'PATCH',{status:'COMPLETED',exerciseMemo:'자세 확인'},changed.token);
    assert.equal((await call('/passes','GET',{},member1.token))[0].remaining_sessions,0);
    await assert.rejects(call('/bookings/'+b2.id,'PATCH',{status:'NO_SHOW'},changed.token));
    const b3=await call('/bookings','POST',{passId:p2.id,trainerId:t.id,startsAt:slot},member2.token);
    await db.query("UPDATE hw2.bookings SET starts_at=date_trunc('hour',now())-interval '2 hours' WHERE id=$1",[b3.id]);
    await call('/bookings/'+b3.id,'PATCH',{status:'NO_SHOW'},changed.token);
    assert.equal((await call('/passes','GET',{},member2.token))[0].remaining_sessions,0);
    const reset=await call('/staff/'+staff.account.id+'/reset-password','POST',{},loggedAdmin.token);
    assert.ok(reset.temporaryPassword);
    await assert.rejects(call('/dashboard','GET',{},changed.token),e=>e.status===401);
    const resetLogin=await call('/auth/login','POST',{email:'staff@example.test',password:reset.temporaryPassword});
    assert.equal(resetLogin.account.must_change_password,true);
    await call('/staff/'+staff.account.id,'PATCH',{active:false},loggedAdmin.token);
    await assert.rejects(call('/auth/login','POST',{email:'staff@example.test',password:reset.temporaryPassword}),e=>e.status===401);
    await assert.rejects(call('/staff/'+admin.id,'PATCH',{active:false},loggedAdmin.token),/마지막 관리자/);
    await call('/auth/logout','POST',{},member1.token);
    await assert.rejects(call('/passes','GET',{},member1.token),e=>e.status===401);
    // 실제 NestJS 라우팅과 HTTP 응답까지 확인합니다.
    process.env.PORT='0';
    app=await bootstrap();
    const address=app.getHttpServer().address();
    const health=await fetch(`http://127.0.0.1:${address.port}/health`);
    assert.equal(health.status,200);
    assert.equal((await health.json()).ok,true);
    const unauth=await fetch(`http://127.0.0.1:${address.port}/passes`);
    assert.equal(unauth.status,401);
    assert.match((await unauth.json()).message,/로그인/);
    await app.close();app=null;
    setupDb=new PGlite();
    pool.query=(q,p)=>setupDb.query(q,p);
    pool.connect=async()=>({query:(q,p)=>setupDb.query(q,p),release(){}});
    process.env.SEED_ADMIN_PASSWORD='SetupAdminPassword123!';
    process.env.SEED_MEMBER_PASSWORD='SetupMemberPassword123!';
    process.env.SEED_TRAINER_PASSWORD='SetupTrainerPassword123!';
    await runSetup('migrate');await runSetup('migrate');
    await runSetup('seed');await runSetup('seed');
    assert.equal((await setupDb.query('SELECT count(*)::int AS n FROM hw2.accounts')).rows[0].n,6);
    assert.equal((await setupDb.query('SELECT count(*)::int AS n FROM hw2.purchased_passes')).rows[0].n,6);
    assert.equal((await setupDb.query('SELECT count(*)::int AS n FROM hw2.bookings')).rows[0].n,3);
  } finally {
    if(app)await app.close();
    pool.query=originalQuery;pool.connect=originalConnect;
    await pool.end();await db.close();if(setupDb)await setupDb.close();
  }
});
